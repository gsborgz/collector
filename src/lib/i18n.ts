export const saveLanguageToStorage = (language: string): void => {
  if (typeof window !== 'undefined') {
    localStorage.setItem('language', language);
  }
};

export const getStoredLanguage = (): string => {
  if (typeof window !== 'undefined') {
    return localStorage.getItem('language') || 'pt';
  }
  return 'pt';
};

